// Whether or not to start a service to respond to network request
// (e.g. for stats collection or otherwise)
pub enum Service {
    On(Option<u16>),
    Off,
}

pub fn run<F>(
    init: init::InitToken,
    debug: bool,
    below_config: &BelowConfig,
    _service: Service,
    command: F,
) -> i32
where
    F: FnOnce(init::InitToken, &BelowConfig, slog::Logger, Receiver<Error>) -> Result<()>,
{
    let (err_sender, err_receiver) = channel();
    let log_path = below_config.log_dir.join("below.log");
    let logger = logging::setup(init, log_path, debug);
    setup_log_on_panic(logger.clone());

    if let Err(e) = record::forward_stop_signals(logger.clone(), err_sender.clone()) {
        error!(logger, "{:#}", e);
        return 1;
    }

    #[cfg(fbcode_build)]
    let _guard = facebook::init(
        init,
        logger.clone(),
        _service,
        below_config.store_dir.clone(),
        err_sender,
    );
    let res = command(init, below_config, logger.clone(), err_receiver);
    record::exit_code(&logger, res)
}

