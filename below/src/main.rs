fn real_main(init: init::InitToken) {
    let opts = Opt::parse();
    let debug = opts.debug;
    config::BELOW_CONFIG
        .set(match BelowConfig::load(&opts.config) {
            Ok(c) => c,
            Err(e) => {
                eprintln!("{:#}", e);
                exit(1);
            }
        })
        .expect("BELOW_CONFIG singleton set twice");
    let below_config = config::BELOW_CONFIG
        .get()
        .expect("BELOW_CONFIG empty after set");

    // Use live mode as default
    let cmd = opts.cmd.as_ref().unwrap_or(&Command::Live {
        interval_s: 5,
        host: None,
        port: None,
    });
    let rc = match cmd {
        Command::External(command) => commands::run_command(init, debug, below_config, command),
        Command::Live {
            interval_s,
            host,
            port,
        } => {
            let host = host.clone();
            let port = *port;
            run(
                init,
                debug,
                below_config,
                Service::Off,
                |_, below_config, logger, errs| {
                    live(
                        init,
                        logger,
                        errs,
                        Duration::from_secs(*interval_s),
                        debug,
                        below_config,
                        host,
                        port,
                    )
                },
            )
        }
        Command::Record { port, args } => {
            logutil::set_current_log_target(logutil::TargetLog::Term);
            run(
                init,
                debug,
                below_config,
                Service::On(*port),
                |init, below_config, logger, errs| {
                    record::record(
                        logger.clone(),
                        errs,
                        below_config,
                        args,
                        debug,
                        Arc::new(statistics::Statistics::new(init)),
                        || {
                            gpu_stats::get_gpu_stats_collector_plugin(
                                init,
                                logger,
                                record::RGPU_INTERVAL,
                            )
                        },
                    )
                },
            )
        }
        Command::Replay {
            time,
            host,
            port,
            yesterdays,
            snapshot,
            source,
        } => {
            let time = time.clone();
            let host = host.clone();
            let port = *port;
            let days_adjuster = yesterdays.clone();
            let snapshots = snapshot.iter().cloned().collect();
            run(
                init,
                debug,
                below_config,
                Service::Off,
                |init, below_config, logger, errs| {
                    let timestamp = cliutil::system_time_from_date_and_adjuster(
                        time.as_str(),
                        days_adjuster.as_deref(),
                    )?;
                    let host = host
                        .map(|host| remote_host::resolve_remote_host(&logger, host, timestamp))
                        .transpose()?;
                    // Replay shows a later sample within this without a warning.
                    let margin = Duration::from_secs(cliutil::MISSING_SAMPLE_WARN_DURATION_S);
                    let (host, snapshots) = commands::find_snapshots(
                        init,
                        source,
                        host.clone(),
                        snapshots,
                        || Ok((timestamp, timestamp)),
                        |time| {
                            store_has_samples_before(
                                &below_config.store_dir,
                                host,
                                port,
                                time + margin,
                            )
                        },
                    )?;
                    let (snapshots, _downloads) =
                        commands::fetch_snapshots(init, snapshots, &errs)?;
                    replay(logger, errs, timestamp, below_config, host, port, snapshots)
                },
            )
        }
        Command::Snapshot {
            begin,
            end,
            duration,
            output,
            host,
            port,
            upload,
        } => {
            let begin = begin.clone();
            let end = end.clone();
            let duration = duration.clone();
            let output = output.clone();
            let host = host.clone();
            let port = *port;
            run(
                init,
                debug,
                below_config,
                Service::Off,
                |init, below_config, logger, _errs| {
                    snapshot(
                        init,
                        logger,
                        below_config,
                        begin,
                        end,
                        duration,
                        output,
                        host,
                        port,
                        upload,
                    )
                },
            )
        }
        Command::Debug { cmd } => match cmd {
            DebugCommand::DumpStore {
                time,
                json,
                strict,
                host,
                port,
            } => {
                let time = time.clone();
                let json = *json;
                let strict = *strict;
                let host = host.clone();
                let port = *port;
                run(
                    init,
                    debug,
                    below_config,
                    Service::Off,
                    |_, below_config, logger, _errs| {
                        dump_store(logger, time, below_config, json, strict, host, port)
                    },
                )
            }
            DebugCommand::DumpStoreRange {
                begin,
                end,
                duration,
                json,
                host,
                port,
            } => {
                let begin = begin.clone();
                let end = end.clone();
                let duration = duration.clone();
                let json = *json;
                let host = host.clone();
                let port = *port;
                run(
                    init,
                    debug,
                    below_config,
                    Service::Off,
                    |_, below_config, logger, _errs| {
                        dump_store_range(
                            logger,
                            below_config,
                            begin,
                            end,
                            duration,
                            json,
                            host,
                            port,
                        )
                    },
                )
            }
            DebugCommand::ConvertStore {
                begin,
                end,
                duration,
                from_store_dir,
                to_store_dir,
                host,
                port,
                compress_opts,
            } => {
                let from_store_dir = from_store_dir.clone();
                let host = host.clone();
                let port = *port;
                run(
                    init,
                    debug,
                    below_config,
                    Service::Off,
                    |_, below_config, logger, _errs| {
                        let (time_begin, time_end) =
                            cliutil::system_time_range_from_date_and_adjuster(
                                begin.as_str(),
                                end.as_deref(),
                                duration.as_deref(),
                                /* days_adjuster */ None,
                            )?;
                        convert_store(
                            logger,
                            below_config,
                            time_begin,
                            time_end,
                            from_store_dir,
                            to_store_dir,
                            host,
                            port,
                            compress_opts,
                            /* redact */ false,
                        )
                        .map(|_| ())
                    },
                )
            }
        },
        Command::Dump {
            host,
            port,
            snapshot,
            source,
            cmd,
        } => {
            let store_dir = below_config.store_dir.clone();
            let host = host.clone();
            let port = *port;
            let snapshots = snapshot.iter().cloned().collect();
            let cmd = cmd.clone();
            run(
                init,
                debug,
                below_config,
                Service::Off,
                |init, _below_config, logger, errs| {
                    let (host, snapshots) = commands::find_snapshots(
                        init,
                        source,
                        host.clone(),
                        snapshots,
                        || {
                            let opts = cmd.general_opts();
                            cliutil::system_time_range_from_date_and_adjuster(
                                opts.begin.as_str(),
                                opts.end.as_deref(),
                                opts.duration.as_deref(),
                                opts.yesterdays.as_deref(),
                            )
                        },
                        |time| store_has_samples_before(&store_dir, host, port, time),
                    )?;
                    let (snapshots, _downloads) =
                        commands::fetch_snapshots(init, snapshots, &errs)?;
                    dump::run(logger, errs, store_dir, host, port, snapshots, cmd)
                },
            )
        }
        Command::Inspect { when, fields } => run(
            init,
            debug,
            below_config,
            Service::Off,
            |_, below_config, logger, _| inspect(logger.clone(), below_config, when, fields),
        ),
        Command::GenerateCompletions { shell, output } => {
            generate_completions(*shell, output.clone())
                .unwrap_or_else(|_| panic!("Failed to generate completions for {:?}", shell));
            0
        }
    };
    exit(rc);
}

fn inspect(
    logger: slog::Logger,
    below_config: &BelowConfig,
    when: &Option<i64>,
    fields: &Vec<model::ModelFieldId>,
) -> Result<()> {
    let timestamp = match *when {
        Some(when) if when > 0 => SystemTime::UNIX_EPOCH
            .checked_add(Duration::from_secs(when as u64))
            .expect("Invalid timestamp"),
        Some(when) => SystemTime::now()
            .checked_sub(Duration::from_secs((-when) as u64))
            .expect("Invalid timestamp"),
        None => SystemTime::now(),
    };
    let fields = if fields.is_empty() {
        &std::io::stdin()
            .lock()
            .lines()
            .map_while(|line| line.ok())
            .filter_map(|line| model::ModelFieldId::from_str(&line).ok())
            .collect()
    } else {
        fields
    };
    let mut store = store::LocalStore::new(logger.clone(), below_config.store_dir.clone());
    let (timestamp, sample) = store
        .get_sample_at_timestamp(timestamp, store::Direction::Reverse)?
        .ok_or(anyhow!("No sample available"))?;

    let model = model::Model::new(timestamp, &sample.sample, None);
    let mut output = serde_json::Map::new();
    for field in fields {
        if let Some(v) = model.query(field) {
            let name = field.to_string();
            match v {
                model::Field::I32(v) => output.insert(name, serde_json::json!(v)),
                model::Field::I64(v) => output.insert(name, serde_json::json!(v)),
                model::Field::U32(v) => output.insert(name, serde_json::json!(v)),
                model::Field::U64(v) => output.insert(name, serde_json::json!(v)),
                model::Field::F32(v) => output.insert(name, serde_json::json!(v)),
                model::Field::F64(v) => output.insert(name, serde_json::json!(v)),
                model::Field::Str(v) => output.insert(name, serde_json::json!(v)),
                _ => None,
            };
        }
    }
    serde_json::to_writer(std::io::stdout(), &output)?;
    Ok(())
}

/// Whether the store `replay` and `dump` read by default, the local one or
/// `host`'s, has samples at or before `time`. A store that rotated `time` out,
/// was wiped since, or can't be read, e.g. because the host is down, has none.
fn store_has_samples_before(
    store_dir: &Path,
    host: Option<String>,
    port: Option<u16>,
    time: SystemTime,
) -> bool {
    let sample = match host {
        Some(host) => store::RemoteStore::new(host, port)
            .and_then(|mut store| store.get_sample_at_timestamp(time, store::Direction::Reverse)),
        // Reading a day the store lacks logs a warning, which the command
        // repeats if it reads the store.
        None => store::LocalStore::new(
            slog::Logger::root(slog::Discard, slog::o!()),
            store_dir.to_path_buf(),
        )
        .get_sample_at_timestamp(time, store::Direction::Reverse),
    };
    matches!(sample, Ok(Some(_)))
}

fn replay(
    logger: slog::Logger,
    errs: Receiver<Error>,
    timestamp: SystemTime,
    below_config: &BelowConfig,
    host: Option<String>,
    port: Option<u16>,
    snapshots: Vec<String>,
) -> Result<()> {
    let mut advance = match (host, snapshots.as_slice()) {
        (None, []) => new_advance_local(logger.clone(), below_config.store_dir.clone(), timestamp),
        (Some(host), []) => new_advance_remote(logger.clone(), host, port, timestamp)?,
        (None, snapshots) => new_advance_snapshots(logger.clone(), snapshots, timestamp)?,
        (Some(_), _) => {
            bail!("--host and --snapshot are incompatible options")
        }
    };

    // Fill the last_sample for forward iteration. If no previous sample exists,
    // this should have no effect.
    advance.initialize();

    let model = match advance.jump_sample_to(timestamp) {
        Some(m) => m,
        None => bail!(
            "No initial sample could be found!\n\
            You may have provided a time in the future or no data was recorded during the provided time. \
            Please check your input and timezone.\n\
            If you are using remote, please make sure the below service on target host is running."
        ),
    };

    cliutil::check_initial_sample_time_with_requested_time(model.timestamp, timestamp);

    let mut view =
        view::View::new_with_advance(model, view::ViewMode::Replay(Arc::new(Mutex::new(advance))));
    logutil::set_current_log_target(logutil::TargetLog::File);

    let sink = view.cb_sink().clone();
    thread::Builder::new()
        .name("replay_err_chan".to_owned())
        .spawn(move || {
            match errs.recv() {
                Ok(e) => {
                    error!(logger, "{:#}", e);
                }
                Err(_) => {
                    error!(logger, "error channel disconnected");
                }
            };
            sink.send(Box::new(|c| c.quit()))
                .expect("Failed to stop view");
        })
        .expect("Failed to spawn thread");

    view.run()
}

fn live_local(
    init: init::InitToken,
    logger: slog::Logger,
    errs: Receiver<Error>,
    interval: Duration,
    debug: bool,
    below_config: &BelowConfig,
) -> Result<()> {
    if let Err(e) = record::bump_memlock_rlimit() {
        warn!(
            logger,
            # "V",
            "Failed to initialize BPF: {}. Data collection will be degraded. \
            You can ignore this warning or try to run with sudo.",
            &e
        );
    };

    let (exit_buffer, bpf_errs) = record::start_exitstat(logger.clone(), debug);
    let mut bpf_err_warned = false;

    let cgroup_bpf = record::start_cgroup_bpf_or_read_files(&logger, below_config, debug);

    let gpu_stats_receiver = if below_config.enable_gpu_stats {
        let gpu_collector =
            gpu_stats::get_gpu_stats_collector_plugin(init, logger.clone(), record::RGPU_INTERVAL)
                .context("Failed to initialize GPU stats collector")?;
        Some(record::start_gpu_stats_thread_and_get_stats_receiver(
            gpu_collector,
            logger.clone(),
            interval,
        )?)
    } else {
        None
    };

    let mut collector = model::Collector::new(
        logger.clone(),
        model::CollectorOptions {
            cgroup_root: below_config.cgroup_root.clone(),
            exit_data: exit_buffer,
            enable_btrfs_stats: below_config.enable_btrfs_stats,
            enable_ethtool_stats: below_config.enable_ethtool_stats,
            enable_ksm_stats: below_config.enable_ksm_stats,
            enable_resctrl_stats: below_config.enable_resctrl_stats,
            process_stack_trace_filter: below_config.process_stack_trace_filter,
            btrfs_samples: below_config.btrfs_samples,
            btrfs_min_pct: below_config.btrfs_min_pct,
            btrfs_commit_root: below_config.btrfs_commit_root,
            gpu_stats_receiver,
            cgroup_bpf,
            ..Default::default()
        },
    );
    logutil::set_current_log_target(logutil::TargetLog::File);
    // Prepare advance obj for pause mode
    let mut adv = new_advance_local(
        logger.clone(),
        below_config.store_dir.clone(),
        SystemTime::now(),
    );
    adv.initialize();
    let mut view = view::View::new_with_advance(
        collector.collect_and_update_model()?,
        view::ViewMode::Live(Arc::new(Mutex::new(adv))),
    );

    let sink = view.cb_sink().clone();

    thread::Builder::new()
        .name("live_collector".to_owned())
        .spawn(move || {
            loop {
                if !bpf_err_warned {
                    bpf_err_warned = record::check_for_exitstat_errors(
                        &logger,
                        bpf_errs
                            .as_ref()
                            .expect("Failed to unwrap bpf_errs receiver"),
                    );
                }

                // Rely on timeout to guarantee interval between samples
                match errs.recv_timeout(interval) {
                    Ok(e) => {
                        error!(logger, "{:#}", e);
                        sink.send(Box::new(|c| c.quit()))
                            .expect("Failed to stop view");
                        return;
                    }
                    Err(RecvTimeoutError::Disconnected) => {
                        error!(logger, "error channel disconnected");
                        sink.send(Box::new(|c| c.quit()))
                            .expect("Failed to stop view");
                        return;
                    }
                    Err(RecvTimeoutError::Timeout) => {}
                };

                match collector.collect_and_update_model() {
                    Ok(model) => {
                        // Error only happens if the other side disconnected - just terminate the thread
                        let data_plane = Box::new(move |s: &mut Cursive| {
                            let view_state = s.user_data::<ViewState>().expect("user data not set");

                            // When paused, no need to update model
                            if !view_state.is_paused() {
                                view_state.update(model);
                            }
                        });
                        if sink.send(data_plane).is_err() {
                            return;
                        }
                    }
                    Err(e) => {
                        error!(logger, "{:#}", e);
                    }
                }
            }
        })
        .expect("Failed to spawn thread");

    view.run()
}

fn live_remote(
    logger: slog::Logger,
    errs: Receiver<Error>,
    interval: Duration,
    host: String,
    port: Option<u16>,
) -> Result<()> {
    let timestamp = SystemTime::now()
        .checked_sub(Duration::from_secs(LIVE_REMOTE_MAX_LATENCY_SEC))
        .expect("Fail to construct timestamp with latency allowance in live remote.");
    let host = remote_host::resolve_remote_host(&logger, host, SystemTime::now())?;
    let mut advance = new_advance_remote(logger.clone(), host, port, timestamp)?;

    advance.initialize();
    let mut view = match advance.get_latest_sample() {
        Some(model) => {
            view::View::new_with_advance(model, view::ViewMode::Live(Arc::new(Mutex::new(advance))))
        }
        None => return Err(anyhow!("No data could be found!")),
    };

    let sink = view.cb_sink().clone();

    thread::Builder::new()
        .name("live_remote_collector".to_owned())
        .spawn(move || {
            loop {
                // Rely on timeout to guarantee interval between samples
                match errs.recv_timeout(interval) {
                    Ok(e) => {
                        error!(logger, "{:#}", e);
                        sink.send(Box::new(|c| c.quit()))
                            .expect("Failed to stop view");
                        return;
                    }
                    Err(RecvTimeoutError::Disconnected) => {
                        error!(logger, "error channel disconnected");
                        sink.send(Box::new(|c| c.quit()))
                            .expect("Failed to stop view");
                        return;
                    }
                    Err(RecvTimeoutError::Timeout) => {}
                };

                let data_plane = Box::new(move |s: &mut Cursive| {
                    let view_state = s.user_data::<ViewState>().expect("user data not set");

                    if let view::ViewMode::Live(adv) = view_state.mode.clone()
                        && let Some(data) = adv
                            .lock()
                            .expect("Lock failed")
                            .advance(store::Direction::Forward)
                    {
                        view_state.update(data)
                    }
                });
                if sink.send(data_plane).is_err() {
                    return;
                }
            }
        })
        .expect("Failed to spawn thread");

    logutil::set_current_log_target(logutil::TargetLog::File);
    view.run()
}

fn live(
    init: init::InitToken,
    logger: slog::Logger,
    errs: Receiver<Error>,
    interval: Duration,
    debug: bool,
    below_config: &BelowConfig,
    host: Option<String>,
    port: Option<u16>,
) -> Result<()> {
    if let Some(host) = host {
        live_remote(logger, errs, interval, host, port)
    } else {
        live_local(init, logger, errs, interval, debug, below_config)
    }
}

#[derive(Debug, Serialize)]
pub struct TimestampedSampleRef<'a> {
    pub timestamp: u64,
    #[serde(borrow)]
    pub sample: &'a model::Sample,
}

impl<'a> TimestampedSampleRef<'a> {
    pub fn new(timestamp: SystemTime, sample: &'a model::Sample) -> Self {
        TimestampedSampleRef {
            timestamp: common::util::get_unix_timestamp(timestamp),
            sample,
        }
    }
}

fn dump_store(
    logger: slog::Logger,
    time: String,
    below_config: &BelowConfig,
    json: bool,
    strict: bool,
    host: Option<String>,
    port: Option<u16>,
) -> Result<()> {
    let timestamp = cliutil::system_time_from_date(time.as_str())?;

    let mut store: Box<dyn Store<SampleType = DataFrame>> = match host {
        Some(host) => Box::new(store::RemoteStore::new(host, port)?),
        None => Box::new(store::LocalStore::new(
            logger.clone(),
            below_config.store_dir.clone(),
        )),
    };

    let (ts, df) = match store.get_sample_at_timestamp(timestamp, store::Direction::Forward) {
        Ok(Some((ts, df))) => (ts, df),
        Ok(None) => bail!("Data not found for requested timestamp"),
        Err(e) => bail!(e),
    };

    if strict && ts != timestamp {
        bail!("Exact requested timestamp not found (would have used next datapoint)");
    }

    let ts_sample = TimestampedSampleRef::new(ts, &df.sample);

    if json {
        println!("{}", serde_json::to_string_pretty(&ts_sample)?);
    } else {
        println!("{:#?}", ts_sample);
    }

    Ok(())
}

fn dump_store_range(
    logger: slog::Logger,
    below_config: &BelowConfig,
    begin: String,
    end: Option<String>,
    duration: Option<String>,
    json: bool,
    host: Option<String>,
    port: Option<u16>,
) -> Result<()> {
    let (time_begin, time_end) = cliutil::system_time_range_from_date_and_adjuster(
        begin.as_str(),
        end.as_deref(),
        duration.as_deref(),
        /* days_adjuster */ None,
    )?;

    let mut store: Box<dyn Store<SampleType = DataFrame>> = match host {
        Some(host) => Box::new(store::RemoteStore::new(host, port)?),
        None => Box::new(store::LocalStore::new(
            logger.clone(),
            below_config.store_dir.clone(),
        )),
    };

    let mut w = BufWriter::new(std::io::stdout());

    let mut current_ts = time_begin;
    while let Some((ts, df)) =
        store.get_sample_at_timestamp(current_ts, store::Direction::Forward)?
    {
        if ts > time_end {
            break;
        }
        let ts_sample = TimestampedSampleRef::new(ts, &df.sample);
        if json {
            serde_json::to_writer(&mut w, &ts_sample)?;
            w.write_all(b"\n")?;
        } else {
            writeln!(&mut w, "{:#?}", ts_sample)?;
        }
        current_ts = ts + Duration::from_secs(1);
        w.flush()?;
    }

    Ok(())
}

fn generate_completions(shell: Shell, output: Option<PathBuf>) -> Result<()> {
    let mut file: Box<dyn io::Write> = match output {
        Some(path) => Box::new(fs::File::create(path)?),
        None => Box::new(io::stdout()),
    };

    let mut app = Opt::command();
    generate(shell, &mut app, "below", &mut file);
    Ok(())
}

fn convert_store(
    logger: slog::Logger,
    below_config: &BelowConfig,
    time_begin: SystemTime,
    time_end: SystemTime,
    from_store_dir: Option<PathBuf>,
    to_store_dir: &Path,
    host: Option<String>,
    port: Option<u16>,
    compress_opts: &record::CompressOpts,
    redact: bool,
) -> Result<Option<SnapshotSamples>> {
    let (timestamp_begin, timestamp_end) = (
        common::util::get_unix_timestamp(time_begin),
        common::util::get_unix_timestamp(time_end),
    );
    let pb = ProgressBar::new(timestamp_end - timestamp_begin);
    // A remote host serves samples it has redacted already, and redacting
    // twice would drop Python script names.
    let redact = redact && host.is_none();

    let mut store: Box<dyn Store<SampleType = DataFrame>> = match (from_store_dir, host) {
        (Some(_from_store_dir), Some(_host)) => {
            bail!("Only one of --from-store-dir and --host should be specified");
        }
        (Some(from_store_dir), None) => {
            pb.set_message(format!("Using local store at {:?}", from_store_dir));
            Box::new(store::LocalStore::new(logger.clone(), from_store_dir))
        }
        (None, Some(host)) => {
            pb.set_message(format!("Using remote store for {}", host));
            Box::new(store::RemoteStore::new(host, port)?)
        }
        (None, None) => {
            pb.set_message(format!("Using local store at {:?}", below_config.store_dir));
            Box::new(store::LocalStore::new(
                logger.clone(),
                below_config.store_dir.clone(),
            ))
        }
    };

    let mut dest_store = store::StoreWriter::new(
        logger.clone(),
        to_store_dir,
        compress_opts.to_compression_mode()?,
        store::Format::Cbor,
    )?;

    pb.set_message(format!("Writing to local store at {:?}", to_store_dir));

    let mut nr_samples = 0;
    let mut samples: Option<SnapshotSamples> = None;
    let mut cur_time = time_begin;
    while cur_time < time_end {
        match store.get_sample_at_timestamp(cur_time, store::Direction::Forward)? {
            Some((frame_time, _)) if frame_time > time_end => break,
            Some((frame_time, mut frame)) => {
                cur_time = frame_time;
                pb.set_message(format!("Storing frame at t = {:?}", frame_time));
                if redact {
                    model::redact::redact_sample(&mut frame.sample);
                }
                dest_store.put(frame_time, &frame)?;
                nr_samples += 1;
                match samples.as_mut() {
                    Some(samples) => {
                        samples.count += 1;
                        samples.last = frame_time;
                    }
                    None => {
                        samples = Some(SnapshotSamples {
                            count: 1,
                            first: frame_time,
                            last: frame_time,
                            hostname: frame.sample.system.hostname,
                        })
                    }
                }
            }
            None => {
                pb.set_message(format!(
                    "Error: Breaking early. Couldn't find any frames after t = {:?}",
                    cur_time
                ));
                break;
            }
        }
        pb.set_position(common::util::get_unix_timestamp(cur_time) - timestamp_begin);
        cur_time += Duration::from_secs(1); // To actually move forward
    }
    pb.set_message(format!("Done. Logged {} samples.", nr_samples));
    Ok(samples)
}

fn snapshot(
    init: init::InitToken,
    logger: slog::Logger,
    below_config: &BelowConfig,
    begin: String,
    end: Option<String>,
    duration: Option<String>,
    output: Option<PathBuf>,
    host: Option<String>,
    port: Option<u16>,
    upload: &commands::SnapshotUpload,
) -> Result<()> {
    let (time_begin, time_end) = cliutil::system_time_range_from_date_and_adjuster(
        begin.as_str(),
        end.as_deref(),
        duration.as_deref(),
        /* days_adjuster */ None,
    )?;
    if let Some(uploader) = commands::snapshot_uploader(init, upload, time_begin, time_end)? {
        return upload_snapshot(
            logger,
            below_config,
            time_begin,
            time_end,
            host,
            port,
            uploader,
        );
    }
    let snapshot = create_snapshot(
        logger,
        below_config,
        time_begin,
        time_end,
        output,
        host,
        port,
        SnapshotPurpose::Local,
    )?;
    println!("Snapshot has been created at {}", snapshot.path.display());
    Ok(())
}

/// Uploads a snapshot tarball made with [`SnapshotPurpose::Upload`].
pub type SnapshotUploader = Box<dyn FnOnce(&Path, SnapshotSamples) -> Result<()>>;

fn upload_snapshot(
    logger: slog::Logger,
    below_config: &BelowConfig,
    time_begin: SystemTime,
    time_end: SystemTime,
    host: Option<String>,
    port: Option<u16>,
    uploader: SnapshotUploader,
) -> Result<()> {
    let temp_dir = TempDir::with_prefix("below_upload.")?;
    let snapshot = create_snapshot(
        logger,
        below_config,
        time_begin,
        time_end,
        Some(temp_dir.path().join("snapshot.tar")),
        host,
        port,
        SnapshotPurpose::Upload,
    )?;
    let Some(samples) = snapshot.samples else {
        bail!(
            "No samples found between {} and {}",
            common::util::systemtime_to_datetime(time_begin),
            common::util::systemtime_to_datetime(time_end),
        );
    };
    println!(
        "Snapshot has {} samples of {} from {} to {}",
        samples.count,
        samples.hostname,
        common::util::systemtime_to_datetime(samples.first),
        common::util::systemtime_to_datetime(samples.last),
    );
    uploader(&snapshot.path, samples)
}

#[derive(Clone, Copy, Debug, PartialEq)]
pub enum SnapshotPurpose {
    /// A file on this host, as `below snapshot` has always written.
    Local,
    /// An upload off the host. Command lines go through
    /// `model::redact::redact_sample`, and the tarball's bytes depend only on
    /// the samples, so uploads of the same samples can be matched by content.
    Upload,
}

pub struct SnapshotFile {
    pub path: PathBuf,
    /// None if there were no samples.
    pub samples: Option<SnapshotSamples>,
}

pub struct SnapshotSamples {
    pub count: usize,
    pub first: SystemTime,
    pub last: SystemTime,
    /// Recorded in the first sample.
    pub hostname: String,
}

/// Write the samples between `time_begin` and `time_end` from the local store,
/// or from `host` if set, to a snapshot tarball that `dump --snapshot` and
/// `replay --snapshot` can read. The tarball is `output` if set and otherwise
/// a new file in the current directory.
pub fn create_snapshot(
    logger: slog::Logger,
    below_config: &BelowConfig,
    time_begin: SystemTime,
    time_end: SystemTime,
    output: Option<PathBuf>,
    host: Option<String>,
    port: Option<u16>,
    purpose: SnapshotPurpose,
) -> Result<SnapshotFile> {
    let (timestamp_begin, timestamp_end) = (
        common::util::get_unix_timestamp(time_begin),
        common::util::get_unix_timestamp(time_end),
    );

    // Create a directory for the output files
    // Format: snapshot_<timestamp_begin>_<timestamp_end>
    let temp_folder = TempDir::with_prefix(format!(
        "snapshot_{:011}_{:011}.",
        timestamp_begin, timestamp_end
    ))
    .context("Failed to create temporary folder for snapshot")?;
    let snapshot_store_path = temp_folder.path();

    // Build compression options to ensure snapshot is compressed before tarball
    let compress_opts = record::CompressOpts {
        compress: true,
        dict_compress_chunk_size: Some(16),
    };
    let samples = convert_store(
        logger,
        below_config,
        time_begin,
        time_end,
        None,
        snapshot_store_path,
        host,
        port,
        &compress_opts,
        purpose == SnapshotPurpose::Upload,
    )
    .context("Failed to convert store for snapshot")?;

    // The temp dir path will be something like "/tmp/snapshot_<timestamp_begin>_<timestamp_end>.XXXX".
    // We will use the dir name as name of the tarball.
    let tarball = if let Some(output) = output {
        output
    } else {
        snapshot_store_path
            .file_name()
            .with_context(|| "path has no filename")?
            .into()
    };
    let file = fs::File::create(&tarball)
        .with_context(|| format!("Failed to create snapshot file {}", tarball.display()))?;
    // Create a new tarball with the snapshot dir name
    let mut tar = TarBuilder::new(file);
    match purpose {
        SnapshotPurpose::Local => tar.append_dir_all("store", snapshot_store_path),
        SnapshotPurpose::Upload => append_store_reproducibly(&mut tar, snapshot_store_path),
    }
    .context("Failed to add snapshot store to tar builder")?;
    tar.finish()
        .context("Failed to build compressed snapshot file.")?;

    Ok(SnapshotFile {
        path: tarball,
        samples,
    })
}

/// Adds `store` so the bytes only depend on the samples in it: fixed file
/// metadata, a fixed order, and no empty shard, like the one the store writer
/// creates for the current day.
fn append_store_reproducibly(tar: &mut TarBuilder<fs::File>, store: &Path) -> io::Result<()> {
    tar.mode(tar::HeaderMode::Deterministic);
    tar.append_dir("store", store)?;
    let mut files = fs::read_dir(store)?
        .map(|entry| Ok(entry?.path()))
        .collect::<io::Result<Vec<_>>>()?;
    files.sort();
    for path in files {
        if fs::metadata(&path)?.len() == 0 {
            continue;
        }
        let name = Path::new("store").join(path.file_name().unwrap_or_default());
        tar.append_path_with_name(&path, name)?;
    }
    Ok(())
}

#[cfg(feature = "enable_backtrace")]
pub fn get_backtrace() -> impl std::fmt::Display {
    std::backtrace::Backtrace::force_capture()
}

#[cfg(not(feature = "enable_backtrace"))]
pub fn get_backtrace() -> impl std::fmt::Display {
    "Backtrace is not available."
}

fn setup_log_on_panic(logger: slog::Logger) {
    std::panic::set_hook(Box::new(move |info| {
        let backtrace = get_backtrace();

        let msg = match info.payload().downcast_ref::<&'static str>() {
            Some(s) => *s,
            None => match info.payload().downcast_ref::<String>() {
                Some(s) => &**s,
                None => "Unknown panic object",
            },
        };

        if logutil::get_current_log_target() == logutil::TargetLog::File {
            logutil::set_current_log_target(logutil::TargetLog::All);
        }

        match info.location() {
            Some(location) => {
                error!(
                    logger,
                    "panic '{}': {}:{}\n{}",
                    msg,
                    location.file(),
                    location.line(),
                    backtrace
                );
            }
            None => {
                error!(logger, "panic '{}'\n{}", msg, backtrace);
            }
        }
    }));
}
